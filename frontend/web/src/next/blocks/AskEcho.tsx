import { formatStamp } from '../data/model.ts'

/**
 * 顶部需求回显框（2026-10-04 · 第 4 项）。
 *
 * ═══ 它解决的是什么 ═══════════════════════════════════════════════════════
 *
 * 结果页原本只有一行小字「按你「…」来配」。那句话把用户的要求压成了一行注脚：
 * 读起来像系统在解释自己，而不像"这是你刚才说的"。于是这一页与"今晚"的关系
 * 全靠一句话撑着，越往后读越像一篇通用文档。
 *
 * 改成一个**框**，把原话本身放回页首，并标上记录时刻：用户一眼能确认
 * 「它拿的是我这句话」。加时刻不是装饰——一轮结果可能几小时后被重新打开，
 * 没有时刻就分不清这是刚点的还是昨天的。
 *
 * ═══ 四条纪律 ════════════════════════════════════════════════════════════
 *
 *   1 **原文照录，不改写、不截断。** 原话是用户本人的字，压成摘要就等于
 *      把"他说了什么"换成"系统认为他说了什么"。长就让它长，它会自然折行。
 *   2 原话为空 ⇒ 整块不渲染。收藏恢复态若没有存下原话，宁可不画这个框，
 *      也不能拿答案正文反推一句像样的"需求"填进去。
 *   3 没有时刻 ⇒ 只显示原话，**不显示时间**。时间是事实，猜一个是错的。
 *   4 它不是导航也不是动作，所以用 <aside>：它是这一页的旁注，不是新章节。
 */
export function AskEcho({ text, at }: { text: string; at?: number | null }) {
  const t = (text ?? '').trim()
  if (!t) return null

  return (
    <aside className="ask-echo">
      <p className="ask-echo-text">{t}</p>
      {at ? <p className="ask-echo-stamp">记录于 {formatStamp(at, Date.now())}</p> : null}
    </aside>
  )
}
