import type { ReactNode } from 'react'

/**
 * 图标。
 *
 * 设计稿的结果页首屏有一行 `[厨师帽] 难度 中等   [叶子] 营养 高   [时钟] 用时 25 分钟`，
 * 三个图标都是**细线描边**风格（约 1.5px 线宽、无填充、圆头圆角），不是实心图形。
 * 这里按那个样式手绘路径，不引入图标库：整站只需要几个，引一个库的代价大于它的价值。
 *
 * **路径表在文件内部，不对外导出**：调用方只能写 `<Icon name="clock" />`，
 * 写不出 `fill`、`stroke-width`、任意 path。图标一旦能被调用方改色改形，
 * 它就不再是"一套图标"，而是一堆各画各的图形——这是本文件唯一的约束。
 *
 * 尺寸与线宽也不由调用方给：它们跟着字号走（1em / 1.4 / 24），
 * 所以图标在任何位置都与旁边的字同高，不会出现"22px 的字配 20px 的图标"这种错配。
 *
 * 2026-09-26 二次修正：首版把厨师帽画成了一个扁圆拱加两横，放大 5 倍看像箩筐——
 * 对照设计稿原版重画：帽冠是**两瓣**（顶部中间有凹陷）+ 一道帽箍，时钟补上秒表顶冠。
 * 教训：凭印象画形状一定会歪，形状类东西必须放大对照原稿。
 */

/** 24×24 视框，细线描边。全部用 currentColor —— 颜色由所在容器决定。 */
