const IMAGE_BASE = '/assets/food/ingredients/'

/* ── 归一化 ────────────────────────────────────────────────────────────
 * 只做"同一个名字的不同写法"合并，不做同义词推断（那是别名表的活）。
 * 折半角放在去标点之前：全角逗号/括号折完就落进半角标点表，一条规则管两种宽度。 */

const FULLWIDTH_SPACE = 0x3000
const FULLWIDTH_START = 0xff01
const FULLWIDTH_END = 0xff5e
const ASCII_OFFSET = 0xfee0

/** 全角折半角：U+FF01..U+FF5E 映射到 ASCII，全角空格折成半角空格。 */
function toHalfWidth(text: string): string {
  let out = ''
  for (const ch of text) {
    const code = ch.codePointAt(0) ?? 0
    if (code === FULLWIDTH_SPACE) out += ' '
    else if (code >= FULLWIDTH_START && code <= FULLWIDTH_END) out += String.fromCharCode(code - ASCII_OFFSET)
    else out += ch
  }
  return out
}

/** 空白与常见标点（中英混排、含全角区之外的中文标点）。 */
const NOISE =
  /[\s\u00b7\u2022\u2027\u30fb.,;:!?'"`^~*+\-_/\\|@#$%&()<>[\]{}，。、；：！？“”‘’（）【】《》〈〉「」『』·—–…～]/g

/** 归一化：折半角 → 去空白与标点 → 去首尾空白。
 *  非字符串（后端可能给回 null/数字）一律落空串，由调用方判未命中——
 *  这一层挡的是**运行时数据**：fridge 来自后端 JSON，类型标注管不到它。 */
export function normalizeName(name: string): string {
  if (!name) return ''
  return toHalfWidth(String(name)).replace(NOISE, '').trim()
}

/* ── 别名索引 ──────────────────────────────────────────────────────── */

function buildAliasIndex(): Map<string, string> {
  const index = new Map<string, string>()
  for (const [canonical, aliases] of Object.entries(INGREDIENTS)) {
    for (const alias of [canonical, ...aliases]) {
      const key = normalizeName(alias)
      // 先登记优先：同一个写法被两个规范名收录时，不静默互相覆盖。
      if (key && !index.has(key)) index.set(key, canonical)
    }
  }
  return index
}

const ALIAS_INDEX: ReadonlyMap<string, string> = buildAliasIndex()
const IMAGE_READY: ReadonlySet<string> = new Set(INGREDIENTS_WITH_IMAGE)

/* ── 出口 ──────────────────────────────────────────────────────────── */

/** 任意写法 → **规范名**；未登记返回 null。
 *  刻意不做模糊匹配、不做前缀猜测：'蛋糕' 不该命中 '蛋'，宁可不配图。 */
export function slugOf(name: string): string | null {
  const key = normalizeName(name)
  if (!key) return null
  return ALIAS_INDEX.get(key) ?? null
}

/** 任意写法 → 图片 URL；未登记、或登记了但没出图，**都返回 null**。
 *
 *  调用方拿到 null 必须只渲染名字：不留空框、不写问号、不发请求。
 *  规范名进 URL 前做 encodeURIComponent——路径里是中文文件名，
 *  这一步让未来任何含特殊字符的规范名也不会把 URL 拼坏。 */
export function ingredientImage(name: string): string | null {
  const canonical = slugOf(name)
  if (canonical === null || !IMAGE_READY.has(canonical)) return null
  return `${IMAGE_BASE}${encodeURIComponent(canonical)}.png`
}
